/**
 * Номера телефонов и chatId — персональные данные, как токен (решение Архитектора):
 * в логи и тексты ошибок не попадают. Номер чата в самом списке и шапке показывать можно.
 */

/** Серии от 7 цифр (номер, chatId, idMessage) → `***`. В текстах ТЗ таких серий нет. */
export function redactIdentifiers(text: string): string {
  return text.replace(/[-+]?\d{7,}/g, '***');
}
