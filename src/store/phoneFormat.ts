/**
 * Заголовок чата по номеру (Р-15, ВА-21): `+7 999 123-45-67`, `+375 29 123-45-67`.
 * Чистая функция; принимает уже нормализованный номер (Р-10), иначе возвращает `+<цифры>`.
 */
export function formatPhone(phone: string): string {
  const d = phone.replace(/\D/g, '');
  let m = /^7(\d{3})(\d{3})(\d{2})(\d{2})$/.exec(d);
  if (m) return `+7 ${m[1] ?? ''} ${m[2] ?? ''}-${m[3] ?? ''}-${m[4] ?? ''}`;
  m = /^375(\d{2})(\d{3})(\d{2})(\d{2})$/.exec(d);
  if (m) return `+375 ${m[1] ?? ''} ${m[2] ?? ''}-${m[3] ?? ''}-${m[4] ?? ''}`;
  return d ? `+${d}` : '';
}
